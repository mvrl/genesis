"""MultiDiffusion-style joint super-resolution over a whole pyramid level.

Motivation (seam removal):
    The default SR descent upscales each parent tile with an *independent* call.
    Siblings (one parent → 2x2 children) share a single draw and are coherent,
    but tiles across parent boundaries come from separate draws → visible seams
    exactly at parent-tile edges.

    MultiDiffusion (Bar-Tal et al. 2023) fixes this at the *generation* step: we
    run one global denoising trajectory over the whole level, covered by many
    overlapping windows whose per-step predictions are fused (averaged) in their
    overlaps. Because every boundary region is co-generated by >=2 windows whose
    trajectories are fused at *each* step, the result is seamless without any
    post-hoc blending.

This is exact in pixel space (the SR model is a pixel-space flow-matching model,
no VAE). We replicate the engine's convention precisely:
    zt = t * x1 + (1 - t) * x0,   t: t_start -> 1,  x1 = clean, x0 = noise
    v_pred = (net(z, t) - z) / (1 - t);   z <- z + dt * v_pred
Seeds (known leaf pixels) are anchored every step at the correct noise level.
"""
from __future__ import annotations

from typing import Dict, List, Optional, Tuple

import numpy as np
import torch
import torch.nn.functional as F
from PIL import Image

TILE_PX = 256
WIN = TILE_PX           # conditioning-parent window size on the coarse mosaic
OUT = 2 * TILE_PX       # SR output per window (512); model upscales 2x


def _pil_to_tensor(pil: Image.Image, device) -> torch.Tensor:
    """[1,3,H,W] in [-1,1] on device."""
    arr = np.asarray(pil.convert("RGB"), np.float32) / 255.0
    t = torch.from_numpy(arr).permute(2, 0, 1).unsqueeze(0)
    return (t * 2.0 - 1.0).to(device)


def _tensor_to_pil(t: torch.Tensor) -> Image.Image:
    x = t.detach().float().cpu()[0].permute(1, 2, 0).numpy()
    x = ((x * 0.5 + 0.5).clip(0, 1) * 255).astype(np.uint8)
    return Image.fromarray(x)


def _cosine_taper(size: int, device, edge_floor: float = 0.08) -> torch.Tensor:
    """2D separable raised-cosine window, [1,1,size,size], min clamped > 0.

    Down-weights window edges so overlapping contributions blend smoothly while
    every pixel still receives non-zero weight (edge_floor keeps borders alive).
    """
    w = torch.hann_window(size, periodic=False, device=device).clamp_min(edge_floor)
    w2 = torch.outer(w, w)
    return w2.view(1, 1, size, size)


def _window_origins(coarse_side: int, stride: int) -> List[int]:
    """Top-left coords for WIN-sized windows tiling [0, coarse_side] at `stride`.

    Always includes the final flush-right window so the far edge is covered.
    """
    if coarse_side <= WIN:
        return [0]
    xs = list(range(0, coarse_side - WIN + 1, stride))
    if xs[-1] != coarse_side - WIN:
        xs.append(coarse_side - WIN)
    return xs


@torch.no_grad()
def multidiffusion_sr_level(
    denoiser,
    coarse_pil: Image.Image,
    device: torch.device,
    *,
    target_zoom: Optional[int],
    steps: int,
    cfg: float,
    t_start: float,
    noise_scale: float,
    dino_weights: str,
    seeds: Optional[Dict[Tuple[int, int], Image.Image]] = None,
    stride_frac: float = 0.5,
    batch: int = 8,
) -> Image.Image:
    """Joint 2x SR of an entire level mosaic via overlapping-window MultiDiffusion.

    Args:
        coarse_pil:  G*256 square mosaic of the level being upscaled.
        target_zoom: child tile zoom (GSD conditioning); None = unknown sentinel.
        steps/cfg/t_start/noise_scale: sampling config (engine convention).
        seeds: optional {(col,row) at child grid: 256x256 PIL} known leaf tiles,
               anchored every step at the correct noise level.
        stride_frac: window stride as a fraction of WIN (0.5 = 50% overlap).

    Returns:
        (2*G*256) square mosaic at the child zoom.
    """
    net = denoiser.net
    use_dino = bool(getattr(net, "use_dino", False))
    coarse = _pil_to_tensor(coarse_pil, device)               # [1,3,C,C]
    C = coarse.shape[-1]
    out_side = 2 * C
    stride = max(1, int(round(WIN * stride_frac)))

    origins = _window_origins(C, stride)
    win_pos: List[Tuple[int, int]] = [(ox, oy) for oy in origins for ox in origins]

    # Per-window conditioning parents (fixed across steps): crop the coarse mosaic.
    parent_crops = torch.cat(
        [coarse[:, :, oy:oy + WIN, ox:ox + WIN] for (ox, oy) in win_pos], dim=0
    )  # [N,3,256,256]
    N = parent_crops.shape[0]

    # DINO features depend only on the parent crop → precompute once (batched).
    dino_feats_all = None
    if use_dino:
        from model_sr import get_dino_embeddings  # available after SR load
        feats = []
        for i in range(0, N, batch):
            feats.append(get_dino_embeddings(parent_crops[i:i + batch], weights_path=dino_weights))
        dino_feats_all = torch.cat(feats, dim=0)

    zoom_vec = None
    if target_zoom is not None:
        zoom_vec = torch.full((N,), float(target_zoom), device=device)

    taper = _cosine_taper(OUT, device)                         # [1,1,512,512]

    # Global init: SDEdit-style warm start from the bicubic 2x of the coarse level.
    bic = F.interpolate(coarse, size=(out_side, out_side), mode="bicubic", align_corners=False)
    noise = noise_scale * torch.randn(1, 3, out_side, out_side, device=device)
    X = t_start * bic + (1.0 - t_start) * noise

    # Seed anchoring: child tiles live on a (2G) grid of 256 px tiles, i.e.
    # exactly the 2x canvas, so a child at (col,row) occupies
    # [row*256:(row+1)*256, col*256:(col+1)*256]. We keep the clean seed pixels
    # plus a fixed noise sample so the known region rides the correct noise
    # level zt = t*x1 + (1-t)*x0 at every step.
    seed_specs = []  # (y0, x0, x1_clean, x0_noise)
    if seeds:
        for (col, row), spil in seeds.items():
            y0, x0 = row * TILE_PX, col * TILE_PX
            x1c = _pil_to_tensor(spil, device)
            x0n = noise_scale * torch.randn_like(x1c)
            seed_specs.append((y0, x0, x1c, x0n))
            X[:, :, y0:y0 + TILE_PX, x0:x0 + TILE_PX] = (
                t_start * x1c + (1.0 - t_start) * x0n
            )

    timesteps = torch.linspace(t_start, 1.0, steps + 1, device=device)
    dt = (1.0 - t_start) / steps

    for si in range(steps):
        t = timesteps[si]
        inv = 1.0 / (1.0 - t + 1e-5)
        V = torch.zeros_like(X)
        Wacc = torch.zeros(1, 1, out_side, out_side, device=device)

        for i in range(0, N, batch):
            sl = slice(i, min(i + batch, N))
            crops = []
            for (ox, oy) in win_pos[sl]:
                cy, cx = 2 * oy, 2 * ox
                crops.append(X[:, :, cy:cy + OUT, cx:cx + OUT])
            zb = torch.cat(crops, dim=0)                       # [b,3,512,512]
            b = zb.shape[0]
            tb = t.expand(b)

            cond = {"parent_img": parent_crops[sl]}
            if use_dino:
                cond["dino_feats"] = dino_feats_all[sl]
            if zoom_vec is not None:
                cond["zoom_level"] = zoom_vec[sl]

            x_cond = net(zb, tb, conditions=cond)
            v = (x_cond - zb) * inv
            if cfg > 1.0:
                uncond = {"dino_feats": None, "parent_img": None, "zoom_level": None}
                x_un = net(zb, tb, conditions=uncond)
                v_un = (x_un - zb) * inv
                v = v_un + cfg * (v - v_un)

            for j, (ox, oy) in enumerate(win_pos[sl]):
                cy, cx = 2 * oy, 2 * ox
                V[:, :, cy:cy + OUT, cx:cx + OUT] += v[j:j + 1] * taper
                Wacc[:, :, cy:cy + OUT, cx:cx + OUT] += taper

        X = X + dt * (V / Wacc.clamp_min(1e-6))

        # Re-anchor seeds at the *next* time level.
        if seed_specs:
            tn = timesteps[si + 1]
            for (y0, x0, x1c, x0n) in seed_specs:
                X[:, :, y0:y0 + TILE_PX, x0:x0 + TILE_PX] = tn * x1c + (1.0 - tn) * x0n

    return _tensor_to_pil(X)
